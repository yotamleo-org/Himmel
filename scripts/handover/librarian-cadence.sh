#!/usr/bin/env bash
# librarian-cadence.sh — the schedule around scripts/handover/librarian.sh, in
# the graphmap-cadence style: a generated cron runner, a flow-run ledger row per
# fire, cadence-alert.sh on a failed run and a clear on a completed one.
#
#   librarian-cadence.sh arm [--every-days N] [--apply] [--force] [--dry-run]
#   librarian-cadence.sh status
#   librarian-cadence.sh disarm [--dry-run]
#
# Cadence is DAILY (04:23) unless --every-days N says otherwise. The runner is a
# DRY RUN (it logs the move list) unless armed with --apply: arming never makes
# the librarian move anything by itself. Arming at all is an operator act; the
# first live --apply needs the luna auto-committer and the Obsidian sync paused.
#
# Seams (tests): LIBRARIAN_CRONTAB, LIBRARIAN_RUNNER_DIR, HIMMEL_OBSERVABILITY_CONFIG,
# plus cadence-alert.sh's own.
# ponytail: cron only (Windows is parked) and day-of-month `*/N` restarts each
# month, so N does not divide evenly across a month end; upgrade path is a
# last-run-age check in the runner.
set -uo pipefail

TASK_NAME="HIMMEL-Librarian"
FLOW="librarian"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HIMMEL_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
# shellcheck source=../lib/observability-registry.sh
. "$HIMMEL_ROOT/scripts/lib/observability-registry.sh"
# shellcheck source=../lib/cadence-format.sh
. "$HIMMEL_ROOT/scripts/lib/cadence-format.sh"
CRONTAB_BIN="${LIBRARIAN_CRONTAB:-crontab}"
RUNNER_DIR="${LIBRARIAN_RUNNER_DIR:-${HOME:-}/.claude/librarian-cadence}"

# "no crontab for <user>" is an empty table; any other read failure is an error
# (installing over it would drop the operator's other jobs).
cron_read() {
    local err
    CRON_TAB=""
    command -v "$CRONTAB_BIN" >/dev/null 2>&1 || return 0
    if CRON_TAB="$(LC_ALL=C "$CRONTAB_BIN" -l 2>&1)"; then return 0; fi
    err="$CRON_TAB"; CRON_TAB=""
    case "$err" in
        *"no crontab"*) return 0 ;;
        *) echo "ERR librarian-cadence: cannot read the crontab: $err" >&2; return 1 ;;
    esac
}
cron_entry() { printf '%s\n' "$CRON_TAB" | grep -F "# $TASK_NAME" || true; }

# The runner a fire executes: the librarian under a flow-run row and the shared
# alert sink. Prints the whole file.
# shellcheck disable=SC2016  # the runner's own $log, $_rc and $(date) stay literal
write_runner_body() {
    local apply="$1" q_flow_lib q_alert_lib
    q_flow_lib=$(printf '%q' "$HIMMEL_ROOT/scripts/lib/flow-run-ledger.sh")
    q_alert_lib=$(printf '%q' "$HIMMEL_ROOT/scripts/luna/cadence-alert.sh")
    printf '#!/usr/bin/env bash\n# librarian runner - generated by librarian-cadence.sh arm\n'
    printf 'PATH=%q\nexport PATH\n' "$PATH"
    printf 'log=%q\n' "$RUNNER_DIR/librarian.log"
    printf '[ -f "$log" ] && mv -f "$log" "$log.prev"\n'
    printf '{\n'
    printf '    echo "[fired $(date '\''+%%Y-%%m-%%d %%H:%%M:%%S'\'')]"\n'
    cadence_posix_leg_start "$q_flow_lib" "$FLOW" "$TASK_NAME"
    printf '    _rc=0; %q %q%s || _rc=$?\n' "$(command -v bash)" "$HIMMEL_ROOT/scripts/handover/librarian.sh" "${apply:+ --apply}"
    cadence_posix_leg_end "$q_flow_lib" "$q_alert_lib" "$FLOW" 0 ""
    printf '    echo "[exit rc=$_rc]"\n'
    printf '} >> "$log" 2>&1\n'
}

cmd_arm() {
    local force=0 dry=0 apply="" days=1 runner entry
    while [ $# -gt 0 ]; do
        case "$1" in
            --every-days) [ $# -ge 2 ] || { echo "ERR librarian-cadence: --every-days needs a number" >&2; return 1; }
                          days="$2"; shift 2 ;;
            --apply) apply=1; shift ;;
            --force) force=1; shift ;;
            --dry-run) dry=1; shift ;;
            *) echo "ERR librarian-cadence: unknown arg: $1" >&2; return 1 ;;
        esac
    done
    case "$days" in ''|*[!0-9]*) echo "ERR librarian-cadence: --every-days must be a whole number of days, 1 to 28" >&2; return 1 ;; esac
    days=$((10#$days))
    { [ "$days" -ge 1 ] && [ "$days" -le 28 ]; } || { echo "ERR librarian-cadence: --every-days must be 1 to 28" >&2; return 1; }
    case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) echo "ERR librarian-cadence: cron only; Windows is parked" >&2; return 2 ;; esac
    command -v "$CRONTAB_BIN" >/dev/null 2>&1 || { echo "ERR librarian-cadence: '$CRONTAB_BIN' not on PATH" >&2; return 2; }
    cron_read || return 4
    if [ -n "$(cron_entry)" ] && [ "$force" -eq 0 ]; then
        echo "ERR librarian-cadence: already armed: $TASK_NAME (use --force to replace)" >&2
        return 3
    fi
    runner="$RUNNER_DIR/librarian-cadence.sh"
    local dom='*'; [ "$days" -gt 1 ] && dom="*/$days"
    local q="'" quoted pct='%'
    quoted="'${runner//"$q"/"'\\''"}'"
    entry="23 4 $dom * * ${quoted//"$pct"/\\%} # $TASK_NAME"
    if [ "$dry" -eq 1 ]; then
        echo "DRY librarian-cadence: would write $runner (${apply:+apply}${apply:-dry-run}) and install: $entry"
        return 0
    fi
    mkdir -p "$RUNNER_DIR" || return 4
    write_runner_body "$apply" > "$runner" || { echo "ERR librarian-cadence: cannot write the runner $runner" >&2; return 4; }
    chmod +x "$runner" || { echo "ERR librarian-cadence: cannot chmod the runner $runner" >&2; return 4; }
    { printf '%s\n' "$CRON_TAB" | { grep -vF "# $TASK_NAME" || true; } | sed '/^$/d'; printf '%s\n' "$entry"; } | "$CRONTAB_BIN" - \
        || { echo "ERR librarian-cadence: crontab install failed" >&2; return 4; }
    observability_register_cadence "$FLOW" $((days * 86400)) "$TASK_NAME"
    echo "librarian-cadence ARMED: every $days day(s) at 04:23, ${apply:+apply}${apply:-dry-run} - $runner"
}

cmd_status() {
    cron_read || return 1
    if [ -n "$(cron_entry)" ]; then echo "ARMED      $TASK_NAME ($(cron_entry | awk '{print $1, $2, $3, $4, $5}'))"
    else echo "not armed  $TASK_NAME"; fi
    [ -f "$RUNNER_DIR/librarian.log" ] && echo "  last run   $(date -r "$RUNNER_DIR/librarian.log" '+%Y-%m-%d %H:%M' 2>/dev/null)"  # swallow-ok: a display-only timestamp, the line just omits it
    return 0
}

cmd_disarm() {
    local dry=0
    [ "${1:-}" = "--dry-run" ] && dry=1
    cron_read || return 4
    if [ -z "$(cron_entry)" ]; then echo "librarian-cadence: nothing armed - disarm is a no-op"; return 0; fi
    if [ "$dry" -eq 1 ]; then echo "DRY librarian-cadence: would remove the $TASK_NAME crontab entry"; return 0; fi
    { printf '%s\n' "$CRON_TAB" | grep -vF "# $TASK_NAME" || true; } | "$CRONTAB_BIN" - || return 4
    rm -f "$RUNNER_DIR/librarian-cadence.sh"
    observability_unregister_cadence "$FLOW" "$TASK_NAME"
    echo "librarian-cadence: disarmed"
}

sub="${1:-}"; [ $# -gt 0 ] && shift
case "$sub" in
    arm) cmd_arm "$@" ;;
    status) cmd_status ;;
    disarm) cmd_disarm "$@" ;;
    *) echo "Usage: librarian-cadence.sh <arm|status|disarm>" >&2; exit 1 ;;
esac
