#!/usr/bin/env node
// Generate docs/credits.md offline; --check refuses a missing or stale page.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

function attribution(text) {
  const section = text.match(/<!-- credits-metadata:start -->([\s\S]*?)<!-- credits-metadata:end -->/);
  if (!section) throw new Error('missing credits metadata in docs/third-party-licenses.md');
  const records = new Map();
  for (const line of section[1].trim().split('\n')) {
    if (!line.startsWith('|')) continue;
    const cells = line.split('|').slice(1, -1).map(cell => cell.trim());
    if (cells[0] === 'Item' || /^-+$/.test(cells[0])) continue;
    if (cells.length !== 5 || !/^(plugin|fork|skill):.+/.test(cells[0])) {
      throw new Error(`malformed credits metadata row: ${line}`);
    }
    const [key, source, author, license, pin] = cells.map(cell => cell === '—' ? '' : cell);
    if (records.has(key)) throw new Error(`duplicate credits metadata: ${key}`);
    records.set(key, { source, author, license, pin });
  }
  return records;
}

function required(value, name, field) {
  if (typeof value !== 'string' || !value.trim()) throw new Error(`${name}: missing ${field}`);
  return value;
}

function cell(value) {
  return value.replace(/&/g, '&amp;').replace(/\|/g, '&#124;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/[\r\n]/g, ' ');
}

function table(rows, fork = false) {
  const header = '| Name | Source | Author | Licence | Pin / tracking |' + (fork ? ' Role |' : '');
  const divider = '|---|---|---|---|---|' + (fork ? '---|' : '');
  return [header, divider, ...rows.sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0).map(row => {
    const values = [row.name, row.source, row.author, row.license, row.pin];
    if (fork) values.push(row.role);
    return '| ' + values.map(cell).join(' | ') + ' |';
  })].join('\n');
}

function generate(root) {
  const read = file => fs.readFileSync(path.join(root, file), 'utf8');
  const plugins = JSON.parse(read('marketplace/.claude-plugin/marketplace.json')).plugins;
  const forks = JSON.parse(read('scripts/guardrails/himmel-adapters.json'));
  const records = attribution(read('docs/third-party-licenses.md'));
  const seen = new Set();
  function take(key) {
    if (seen.has(key)) throw new Error(`duplicate inventory item: ${key}`);
    seen.add(key);
    return records.get(key) || {};
  }
  function complete(row) {
    for (const field of ['name', 'source', 'author', 'license', 'pin']) required(row[field], row.name, field);
    if (!/^https:\/\//.test(row.source)) throw new Error(`${row.name}: source must be an HTTPS URL`);
    return row;
  }
  const pluginRows = plugins.map(plugin => {
    const extra = take(`plugin:${plugin.name}`);
    const remote = typeof plugin.source === 'object' && plugin.source !== null ? plugin.source : null;
    return complete({
      name: plugin.name,
      source: (remote?.url || extra.source || '').replace(/\.git$/, ''),
      author: extra.author || plugin.author?.name,
      license: plugin.license || extra.license,
      pin: remote ? (remote.sha || remote.ref || 'Not pinned in marketplace') : (extra.pin || 'In-tree'),
    });
  });
  const forkRows = forks.map(fork => {
    const extra = take(`fork:${fork.nwo}`);
    const pin = fork.pin_site ? `branch ${fork.himmel_branch}; [pin site](../${fork.pin_site})` : `branch ${fork.himmel_branch}; no pin site registered`;
    return complete({
      name: fork.nwo,
      source: `https://github.com/${required(fork.upstream, fork.nwo, 'upstream')}`,
      author: extra.author || fork.upstream.split('/')[0],
      license: extra.license,
      pin,
      role: required(fork.role, fork.nwo, 'role'),
    });
  });
  const skills = [];
  for (const [key, extra] of records) {
    if (key.startsWith('skill:')) skills.push(complete({ name: key.slice(6), ...extra }));
    else if (!seen.has(key)) throw new Error(`unused credits metadata: ${key}`);
  }
  return `# Credits

himmel builds on the work of the authors and communities below. Thank you.
This inventory includes opt-in plugins, not just the active plugin profile.
The fork registry also includes dormant and contribution-only repositories;
the role column distinguishes those from runtime dependencies.

<!-- Generated by scripts/docs/generate-credits.mjs. Do not edit by hand. -->

## Plugins and their skill families

One row per entry in [the marketplace manifest](../marketplace/.claude-plugin/marketplace.json).
A plugin row credits its bundled skill family; it is not a claim that every
skill is enabled. Remote pins come directly from the manifest. In-tree
vendoring records name the upstream pins and carried deviations.

${table(pluginRows)}

## Standalone skill families

These are the vendored skills outside marketplace plugins, recorded in
[the third-party attribution audit](third-party-licenses.md#credits-metadata).

${table(skills)}

## Forks

One row per entry in [the fork adapter registry](../scripts/guardrails/himmel-adapters.json).
The name identifies our fork; Source links to its upstream. Tracking branches
are mutable, not immutable pins. Where registered, the pin-site link is the
source of truth for the shipped revision; no pin is invented for dormant forks.

${table(forkRows, true)}

## Licences and regeneration

This is an attribution index, not a relicensing or compatibility verdict.
An unknown or undeclared licence grants no permission to copy that source.
Mixed and source-available terms remain visible rather than being labelled MIT.
Retained licence texts and the direct npm dependency audit are in
[Third-party licences](third-party-licenses.md).

Generate from the checked-in sources (Node.js, no network):

\`\`\`bash
node scripts/docs/generate-credits.mjs
node scripts/docs/generate-credits.mjs --check
\`\`\`

When adding a plugin or fork, record any missing attribution fields in the
credits metadata table in \`docs/third-party-licenses.md\`, then regenerate.
The check rejects missing rows, changed pins, missing licence metadata and
unused plugin/fork metadata. \`scripts/docs/test-generate-credits.sh\` runs it
against this tree as well as missing-row fixtures in CI.
`;
}

try {
  const { values } = parseArgs({ options: {
    root: { type: 'string', default: fileURLToPath(new URL('../../', import.meta.url)) },
    check: { type: 'boolean', default: false },
  } });
  const root = path.resolve(values.root);
  const expected = generate(root);
  const output = path.join(root, 'docs/credits.md');
  if (values.check) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== expected) {
      throw new Error('docs/credits.md is missing or stale; run node scripts/docs/generate-credits.mjs');
    }
    console.log('credits: current; every shipped plugin and registered fork has a row');
  } else {
    fs.writeFileSync(output, expected);
    console.log('credits: generated docs/credits.md');
  }
} catch (error) {
  console.error(`credits: ${error.message}`);
  process.exitCode = 1;
}
