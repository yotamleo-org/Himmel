#!/usr/bin/env bash
# graph-choices-cadence.sh -- arm, report and disarm the HIMMEL-GraphChoices cron row: one daily fire of
# scripts/graphify/graph-choices-pass.sh, the pass that runs the repos and accounts a user chose.
#
#   graph-choices-cadence.sh arm|status|disarm [--time HH:MM] [--force] [--dry-run]
#
# Arming is the opt-in: storing a choice spends nothing, and this row is the only thing that fires the pass. The
# default time is 04:40. `arm` refuses to replace a row already armed unless --force (which also re-renders the runner
# after a runner-format bump). `arm --dry-run` prints the row it would install and writes nothing.
#
# The runner follows graphmap-cadence.sh's: it pins the node, graphify, claude and bun directories on PATH, carries
# cadence_oauth_token_lines (cron cannot log in on macOS without a token), and passes an empty flow so its end-of-run
# line neither clears nor raises what the pass itself alerted. Its files live in ~/.claude/graph-choices-cadence/; the
# log keeps the pass's lines across fires (rotated by size), because the doctor counts consecutive words over it.
#
# Exit: 0 done (armed, already armed, status, disarmed, dry run); 1 a bad argument or --time; 2 a missing tool at arm
# time (bash, node or graphify) or a crontab that could not be read; 4 the crontab install failed, the rejected tab is
# left in TMPDIR.
#
# Seams (tests): GRAPH_CHOICES_CRONTAB (command invoked instead of `crontab`), GRAPH_CHOICES_BAT_DIR (the runner dir).
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HIMMEL_ROOT="$(cd "$HERE/../.." && pwd)"
# shellcheck source=../lib/cadence-format.sh
. "$HIMMEL_ROOT/scripts/lib/cadence-format.sh"

TASK="HIMMEL-GraphChoices"
CRONTAB_BIN="${GRAPH_CHOICES_CRONTAB:-crontab}"
BAT_DIR="${GRAPH_CHOICES_BAT_DIR:-$(cadence_user_home)/.claude/graph-choices-cadence}"
RUNNER="$BAT_DIR/graph-choices.sh"
LOG="$BAT_DIR/graph-choices.log"
PASS="$HERE/graph-choices-pass.sh"
LOG_MAX_BYTES=200000
DEFAULT_TIME="04:40"

SUBCMD="${1:-}"
[ $# -eq 0 ] || shift
TIME="$DEFAULT_TIME" FORCE=0 DRY_RUN=0
while [ $# -gt 0 ]; do
  case "$1" in
    --time) TIME="${2:-}"; shift 2 || { echo "ERR graph-choices-cadence: --time needs HH:MM" >&2; exit 1; } ;;
    --force) FORCE=1; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    *) echo "ERR graph-choices-cadence: unknown argument: $1" >&2; exit 1 ;;
  esac
done
case "$SUBCMD" in arm | status | disarm) ;; *) echo "usage: graph-choices-cadence.sh arm|status|disarm [--time HH:MM] [--force] [--dry-run]" >&2; exit 1 ;; esac
if ! grep -Eq '^([01][0-9]|2[0-3]):[0-5][0-9]$' <<<"$TIME"; then
  echo "ERR graph-choices-cadence: --time must be HH:MM on a 24-hour clock (got '$TIME')" >&2
  exit 1
fi

CRON_TAB=""
cron_read() {
  local err rc=0
  err="$(mktemp "${TMPDIR:-/tmp}/graph-choices-cadence.err.XXXXXX")"
  CRON_TAB="$(LC_ALL=C "$CRONTAB_BIN" -l 2>"$err")" || rc=$?
  if [ "$rc" -ne 0 ]; then
    if [ "$rc" -eq 1 ] && { [ ! -s "$err" ] || grep -qi 'no crontab' "$err"; }; then
      CRON_TAB=""
    else
      echo "ERR graph-choices-cadence: crontab -l failed (rc=$rc); refusing to treat it as an empty crontab" >&2
      rm -f "$err"
      exit 2
    fi
  fi
  rm -f "$err"
}

cron_install() { # <tab file>
  local tab="$1"
  if ! "$CRONTAB_BIN" - <"$tab"; then
    echo "ERR graph-choices-cadence: crontab install failed; the rejected tab is left at $tab" >&2
    return 4
  fi
  rm -f "$tab"
}

row_now() { printf '%s\n' "$CRON_TAB" | grep -E "# ${TASK}\$" | head -n 1 || true; }

dir_of() { local b; b="$(command -v "$1" 2>/dev/null)" || return 1; case "$b" in /*) dirname "$b" ;; *) return 1 ;; esac; }

# shellcheck disable=SC2016  # the runner's own $vars are emitted literally
emit_runner() { # <node dir> <graphify dir> <claude dir> <bun dir> <bash bin>
  local dir
  printf '#!/bin/sh\n'
  printf '# %s runner -- generated by graph-choices-cadence.sh arm\n' "$TASK"
  printf '# %s %s\n' "$CADENCE_FORMAT_MARKER" "$CADENCE_RUNNER_FORMAT_VERSION"
  for dir in "$1" "$2" "$3" "$4"; do
    [ -z "$dir" ] || printf 'export PATH=%s:$PATH\n' "$(printf '%q' "$dir")"
  done
  cadence_oauth_token_lines
  printf 'log=%s\n' "$(printf '%q' "$LOG")"
  printf 'if [ -f "$log" ] && [ "$(wc -c < "$log" | tr -d " ")" -gt %s ]; then\n' "$LOG_MAX_BYTES"
  printf '    mv -f "$log" "$log.prev"\n'
  printf 'fi\n'
  printf '{\n'
  printf '    echo "[fired $(date "+%%Y-%%m-%%d %%H:%%M:%%S")]"\n'
  printf '    cd %s || exit 1\n' "$(printf '%q' "$HIMMEL_ROOT")"
  printf '    _rc=0; %s %s || _rc=$?\n' "$(printf '%q' "$5")" "$(printf '%q' "$PASS")"
  printf '    echo "[exit rc=$_rc]"\n'
  printf '} >> "$log" 2>&1\n'
}

cmd_arm() {
  local bash_bin node_dir graphify_dir claude_dir bun_dir mm hh entry tab tmp
  bash_bin="$(command -v bash 2>/dev/null)" || { echo "ERR graph-choices-cadence: bash is not on PATH at arm time" >&2; exit 2; }
  node_dir="$(dir_of node)" || { echo "ERR graph-choices-cadence: node is not on PATH at arm time" >&2; exit 2; }
  graphify_dir="$(dir_of graphify)" || { echo "ERR graph-choices-cadence: graphify is not on PATH at arm time; the free structure pass needs it" >&2; exit 2; }
  claude_dir="$(dir_of claude)" || claude_dir=""
  bun_dir="$(dir_of bun)" || bun_dir=""
  mm=$((10#${TIME#*:})) hh=$((10#${TIME%:*}))
  entry="$mm $hh * * * $(printf '%q' "$RUNNER") # $TASK"
  cron_read
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "DRY graph-choices-cadence: would install the cron row: $entry"
    echo "DRY graph-choices-cadence: would write the runner $RUNNER (pass $PASS)"
    echo "DRY graph-choices-cadence: no changes made"
    return 0
  fi
  if [ -n "$(row_now)" ] && [ "$FORCE" -ne 1 ]; then
    echo "graph-choices-cadence: $TASK is already armed; --force re-renders the runner and the row"
    return 0
  fi
  mkdir -p "$BAT_DIR" || exit 1
  tmp="$(mktemp "$BAT_DIR/runner.XXXXXX")" || exit 1
  emit_runner "$node_dir" "$graphify_dir" "$claude_dir" "$bun_dir" "$bash_bin" >"$tmp"
  chmod 700 "$tmp" || exit 1
  tab="$(mktemp "${TMPDIR:-/tmp}/graph-choices-cadence.cron.XXXXXX")" || exit 1
  { printf '%s\n' "$CRON_TAB" | grep -vE "# ${TASK}\$" || true; printf '%s\n' "$entry"; } >"$tab"
  cron_install "$tab" || { rm -f "$tmp"; exit 4; }
  mv -f "$tmp" "$RUNNER" || exit 1  # prim-ok: publish the staged runner after cron succeeds; atomic_write would reset its executable mode
  cadence_prov_record "$TASK"
  echo "graph-choices-cadence: armed $TASK daily at $TIME -> $PASS"
  echo "Spend worst case, from the stored graph choice:"
  node "$HIMMEL_ROOT/scripts/himmelctl/lib/graph-choices.js" worst-case | sed 's/^/  /'
  echo "Disarm anytime with: bash scripts/graphify/graph-choices-cadence.sh disarm"
}

cmd_status() {
  local entry stamp last_fired last_exit
  cron_read
  entry="$(row_now)"
  if [ -n "$entry" ]; then
    echo "ARMED      $TASK (cron: $(printf '%s' "$entry" | awk '{print $1, $2, $3, $4, $5}'))"
  else
    echo "not armed  $TASK"
  fi
  if [ -f "$RUNNER" ]; then
    stamp="$(grep -oE "${CADENCE_FORMAT_MARKER}[[:space:]]*[0-9]+" "$RUNNER" | head -n 1 | grep -oE '[0-9]+$' || true)"
    echo "runner     $RUNNER (format ${stamp:-unstamped}, current $CADENCE_RUNNER_FORMAT_VERSION)"
  fi
  if [ -f "$LOG" ]; then
    last_fired="$(grep -E '^\[fired ' "$LOG" | tail -n 1 || true)"
    last_exit="$(grep -E '^\[exit rc=' "$LOG" | tail -n 1 || true)"
    echo "last run   ${last_fired:-no fire recorded} ${last_exit:-}"
  fi
}

cmd_disarm() {
  local tab
  cron_read
  if [ -z "$(row_now)" ]; then
    echo "graph-choices-cadence: $TASK is not armed; nothing to disarm"
    [ "$DRY_RUN" -eq 1 ] || rm -f "$RUNNER"
    return 0
  fi
  if [ "$DRY_RUN" -eq 1 ]; then
    echo "DRY graph-choices-cadence: would remove the cron row: $(row_now)"
    echo "DRY graph-choices-cadence: no changes made"
    return 0
  fi
  tab="$(mktemp "${TMPDIR:-/tmp}/graph-choices-cadence.cron.XXXXXX")" || exit 1
  printf '%s\n' "$CRON_TAB" | grep -vE "# ${TASK}\$" >"$tab" || true
  cron_install "$tab" || exit 4
  rm -f "$RUNNER"
  echo "graph-choices-cadence: $TASK disarmed (the log stays at $LOG)"
}

case "$SUBCMD" in
  arm) cmd_arm ;;
  status) cmd_status ;;
  disarm) cmd_disarm ;;
esac
